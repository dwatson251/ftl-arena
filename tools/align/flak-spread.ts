/** Flak's spread circle round its target (and while aiming). Usage: ARENA_URL=... npx tsx tools/align/flak-spread.ts */
import { chromium } from "playwright";
const URL = process.env.ARENA_URL ?? "http://localhost:5173";
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 1280, height: 720 }, deviceScaleFactor: 2 })).newPage();
p.on("pageerror", (e) => console.log("pageerror:", e.message));
await p.addInitScript(() => localStorage.getItem("ftl-arena-name") || localStorage.setItem("ftl-arena-name", "Captain"));
await p.goto(URL);
await p.waitForSelector("#loading", { state: "detached", timeout: 60000 });
await p.click('[data-open="single"]');
await p.waitForSelector(".hg-step");
await p.waitForTimeout(400);
await p.fill('input[data-cfg="scrap"]', "2000");
await p.press('input[data-cfg="scrap"]', "Enter");
await p.waitForTimeout(400);
await p.click('button[data-step="Weapons"]');
await p.waitForTimeout(400);
await p.$eval('button[data-buy="SHOTGUN"]', (el) => (el as HTMLButtonElement).click());
await p.waitForTimeout(400);
await p.locator(".hg-step", { hasText: "Launch" }).click();
await p.click('button[data-ready="1"]');
const force = await p.waitForSelector('button[data-force="1"]', { timeout: 1500 }).catch(() => null);
if (force) await force.click();
await p.waitForFunction(() => !document.querySelector(".hg-step"), null, { timeout: 20000 });
await p.waitForTimeout(1500);
const slot = await p.evaluate(() => { const a = (window as any).__arena; const v = a.view(); const s = v.ships[v.you].weapons.findIndex((w: any) => w.bp === "SHOTGUN"); a.send({ c: "weaponPower", slot: s, on: true }); a.send({ c: "target", slot: s, target: { kind: "room", room: 0 } }); return s; });
console.log("flak in slot", slot);
await p.waitForTimeout(1000);
await p.screenshot({ path: "traces/controller/9-flak-spread.png", clip: { x: 650, y: 130, width: 290, height: 400 } });
await b.close();
