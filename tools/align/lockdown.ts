/** Crystal Lockdown: the LOCKDOWN button, the crystal coat round the room, then it shattering. traces/lockdown/ */
import { mkdirSync } from "node:fs";
import { chromium } from "playwright";
const URL = process.env.ARENA_URL ?? "http://localhost:5173";
mkdirSync("traces/lockdown", { recursive: true });
const b = await chromium.launch({ args: ["--autoplay-policy=no-user-gesture-required"] });
const p = await (await b.newContext({ viewport: { width: 1280, height: 720 }, deviceScaleFactor: 2 })).newPage();
p.on("pageerror", (e) => console.log("pageerror:", e.message));
await p.addInitScript(() => localStorage.getItem("ftl-arena-name") || localStorage.setItem("ftl-arena-name", "Captain"));
await p.goto(URL);
await p.waitForSelector("#loading", { state: "detached", timeout: 60000 });
await p.click('[data-open="single"]');
await p.waitForSelector(".hg-step");
await p.waitForTimeout(400);
await p.click('button[data-step="Ship"]');
await p.waitForTimeout(300);
await p.$eval('button[data-ship="PLAYER_SHIP_CRYSTAL"]', (el) => (el as HTMLButtonElement).click());
await p.waitForTimeout(400);
await p.locator(".hg-step", { hasText: "Launch" }).click();
await p.click('button[data-ready="1"]');
const force = await p.waitForSelector('button[data-force="1"]', { timeout: 1500 }).catch(() => null);
if (force) await force.click();
await p.waitForFunction(() => !document.querySelector(".hg-step"), null, { timeout: 20000 });
await p.waitForTimeout(1500);
await p.screenshot({ path: "traces/lockdown/1-button.png", clip: { x: 0, y: 150, width: 260, height: 200 } });
const id = await p.evaluate(() => { const a = (window as any).__arena; const v = a.view(); const c = v.ships[v.you].crew.find((q: any) => q.race === "crystal"); if (c) a.send({ c: "lockdown", crew: c.id }); return c?.id; });
console.log("crystal crew:", id);
await p.waitForTimeout(1200);
console.log("lockdowns:", JSON.stringify(await p.evaluate(() => { const v = (window as any).__arena.view(); return v.ships[v.you].lockdowns; })));
await p.screenshot({ path: "traces/lockdown/2-sealed.png", clip: { x: 100, y: 180, width: 560, height: 330 } });
await b.close();
