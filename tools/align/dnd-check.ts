/** Hangar drag-and-drop + sticky slot check: npx tsx tools/align/dnd-check.ts (server + client running) */
import { chromium } from "playwright";
const browser = await chromium.launch();
const p = await (await browser.newContext({ viewport: { width: 1280, height: 720 } })).newPage();
p.on("pageerror", (e) => console.log("pageerror:", e.message));
await p.goto("http://localhost:5173");
await p.waitForSelector("#practice:not([disabled])");
await p.click("#practice");
await p.waitForSelector(".hg-step");
await p.waitForTimeout(2500);
await p.click('button[data-step="Weapons"]');
await p.waitForTimeout(300);
const names = () => p.$$eval(".wslot b", (b) => b.map((x) => x.textContent));
console.log("before", await names());
await p.dragAndDrop('.wcard[data-drag="buy:LASER_HEAVY_1"]', '.wslot[data-slot="2"]');
await p.waitForTimeout(400);
console.log("after buy-drop", await names());
await p.dragAndDrop('.wslot[data-slot="2"]', '.wslot[data-slot="0"]');
await p.waitForTimeout(400);
console.log("after reorder", await names());
await p.dragAndDrop('.wslot[data-slot="0"]', ".shop-drop .wcard >> nth=5");
await p.waitForTimeout(400);
console.log("after sell-drop", await names());
await p.$eval(".hg-main", (m) => (m.scrollTop = 900));
await p.waitForTimeout(200);
const top = await p.$eval(".wslots-sticky", (e) => e.getBoundingClientRect().top);
console.log("sticky slots top after scrolling:", Math.round(top));
await p.screenshot({ path: "traces/align/hangar-scrolled.png" });
await browser.close();
